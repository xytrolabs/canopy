#!/usr/bin/env python3
"""Generate the Canopy window decoration theme (labwc / openbox-3).

labwc looks for titlebar button images under a fixed set of names:

    <button>[-<toggled>][_hover]-<active|inactive>.png|svg|xbm

so a file called ``close-unpressed.svg`` is never loaded and the button falls
back to labwc's built-in glyph, tinted with the theme colour. That fallback is
what made the decorations look dated. This script writes properly named PNGs
plus the themerc that goes with them.

The result is a macOS-style traffic light set on the left of a flat, rounded
titlebar that uses the Canopy palette:

    $ python3 scripts/gen-window-theme.py [out-dir]

Default output: config/labwc/themes/canopy/openbox-3
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw

# --------------------------------------------------------------------- tokens --
# Kept in sync with src/theme/builtin_palettes.cpp ("Canopy").
SURFACE = "#16151F"
SURFACE_VARIANT = "#201E2C"
ON_SURFACE = "#F2F0F7"
ON_SURFACE_VARIANT = "#A9A5BB"
OUTLINE = "#2E2B3D"
ACCENT = "#7C5CFC"

TITLE_ACTIVE = SURFACE_VARIANT
TITLE_INACTIVE = "#1B1924"
BORDER_ACTIVE = OUTLINE
BORDER_INACTIVE = "#241F31"
LABEL_ACTIVE = ON_SURFACE
LABEL_INACTIVE = ON_SURFACE_VARIANT

# macOS traffic lights: (dot, hover dot, glyph ink).
CLOSE = ("#FF5F57", "#FF8A84", "#4C0B06")
ICONIFY = ("#FEBC2E", "#FFD470", "#4C3B04")
MAXIMIZE = ("#28C840", "#5AE070", "#04430F")
INACTIVE_DOT = "#4A4A55"
INACTIVE_DOT_HOVER = "#5B5B69"

CANVAS = 14          # button image size
RADIUS = 6           # dot radius inside the canvas
SUPERSAMPLE = 4      # draw big, downscale for smooth edges


def rgb(value: str) -> tuple[int, int, int]:
    """#rrggbb -> (r, g, b)."""
    value = value.lstrip("#")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def dot(colour: str, glyph: str | None = None, glyph_colour: str | None = None) -> Image.Image:
    """A filled circle, optionally with a small centred glyph cut into it."""
    size = CANVAS * SUPERSAMPLE
    image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    c = size / 2
    r = RADIUS * SUPERSAMPLE
    draw.ellipse((c - r, c - r, c + r, c + r), fill=rgb(colour))

    if glyph is not None:
        g = 5.0 * SUPERSAMPLE        # glyph half-extent
        lw = max(2, SUPERSAMPLE * 3 // 2)
        dark = rgb(glyph_colour or "#000000")
        if glyph == "close":
            draw.line((c - g, c - g, c + g, c + g), fill=dark, width=lw)
            draw.line((c - g, c + g, c + g, c - g), fill=dark, width=lw)
        elif glyph == "iconify":
            draw.line((c - g, c, c + g, c), fill=dark, width=lw)
        elif glyph == "max":
            draw.line((c - g, c, c + g, c), fill=dark, width=lw)
            draw.line((c, c - g, c, c + g), fill=dark, width=lw)
        elif glyph == "restore":
            # Two small corner brackets, like the macOS "restore" state.
            draw.polygon(
                [(c - g, c - g), (c - g * 0.1, c - g), (c - g, c - g * 0.1)],
                fill=dark,
            )
            draw.polygon(
                [(c + g, c + g), (c + g * 0.1, c + g), (c + g, c + g * 0.1)],
                fill=dark,
            )

    return image.resize((CANVAS, CANVAS), Image.LANCZOS)


def write_buttons(out: Path) -> list[str]:
    """Write every button image labwc may ask for, for both focus states."""
    written: list[str] = []
    buttons = {
        "close": (CLOSE, "close"),
        "iconify": (ICONIFY, "iconify"),
        "max": (MAXIMIZE, "max"),
        "max_toggled": (MAXIMIZE, "restore"),
    }

    for name, ((dot_colour, hover_colour, glyph_colour), glyph) in buttons.items():
        variants = {
            f"{name}-active.png": dot(dot_colour),
            f"{name}-inactive.png": dot(INACTIVE_DOT),
            f"{name}_hover-active.png": dot(hover_colour, glyph, glyph_colour),
            f"{name}_hover-inactive.png": dot(INACTIVE_DOT_HOVER, glyph, "#1A1A20"),
        }
        for filename, image in variants.items():
            image.save(out / filename)
            written.append(filename)

    return written


def write_themerc(out: Path) -> None:
    text = f"""# Canopy window decoration - generated by scripts/gen-window-theme.py
#
# Flat, rounded titlebar in the Canopy palette with macOS traffic lights.
# Button images are PNGs named the way labwc expects
# (<button>[-<toggled>][_hover]-<active|inactive>.png); the colours live in the
# images, so there is deliberately no `image.color` tinting here - tinting is
# what made the old theme fall back to labwc's generic glyphs.

border.width: 1

window.active.border.color: {BORDER_ACTIVE}
window.inactive.border.color: {BORDER_INACTIVE}

window.active.title.bg: flat solid
window.active.title.bg.color: {TITLE_ACTIVE}
window.inactive.title.bg: flat solid
window.inactive.title.bg.color: {TITLE_INACTIVE}

window.active.label.bg: parentrelative
window.inactive.label.bg: parentrelative
window.label.text.justify: center
window.active.label.text.color: {LABEL_ACTIVE}
window.inactive.label.text.color: {LABEL_INACTIVE}

# Traffic lights: the images carry the colour, the hover ring is drawn behind
# them and stays invisible until the pointer is on the button.
window.button.width: {CANVAS}
window.button.height: {CANVAS}
window.button.spacing: 8
window.button.hover.bg.color: #FFFFFF14
window.button.hover.bg.corner-radius: {CANVAS // 2}

# Fallback tints, used only if an image is missing.
window.active.button.unpressed.image.color: {ON_SURFACE}
window.inactive.button.unpressed.image.color: {ON_SURFACE_VARIANT}

window.active.shadow.size: 24
window.inactive.shadow.size: 12
window.active.shadow.color: #00000066
window.inactive.shadow.color: #00000033

menu.border.width: 1
menu.border.color: {BORDER_ACTIVE}
menu.items.bg: flat solid
menu.items.bg.color: {TITLE_ACTIVE}
menu.items.text.color: {LABEL_ACTIVE}
menu.items.active.bg: flat solid
menu.items.active.bg.color: {ACCENT}
menu.items.active.text.color: #FFFFFF
menu.separator.color: {OUTLINE}
menu.title.bg: flat solid
menu.title.bg.color: {TITLE_ACTIVE}
menu.title.text.color: {LABEL_ACTIVE}
menu.title.text.justify: center
"""
    (out / "themerc").write_text(text, encoding="utf-8")


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else Path(__file__).resolve().parent.parent / (
        "config/labwc/themes/canopy/openbox-3"
    )
    out.mkdir(parents=True, exist_ok=True)

    # Old, unused assets: labwc never looked these names up.
    stale: set[Path] = set()
    for pattern in ("*-unpressed.svg", "*-hover.svg", "*-pressed.svg", "*-toggled.svg",
                    "*-toggled-unpressed.svg", "restore-*.xbm"):
        stale.update(out.glob(pattern))
    for path in stale:
        path.unlink(missing_ok=True)

    buttons = write_buttons(out)
    write_themerc(out)
    print(f"theme: {out}")
    for name in sorted(buttons):
        print(f"  {name}")
    print("  themerc")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))