import os, json, collections

import os as _os
# ICON_PREFIX lets an image build index themes inside a staging root
# (DESTDIR=/tmp/img) while still writing the paths the shell will see at
# runtime (/usr/share/icons/...). Without it the map would be generated from the
# build machine and point at files that do not exist in the image, which shows
# up as every icon falling back to a letter glyph.
PREFIX = _os.environ.get("ICON_PREFIX", "")
def rooted(p):
    return _os.path.join(PREFIX, p.lstrip("/")) if PREFIX else p

HOME = _os.path.expanduser("~")
USER_ICONS = _os.path.join(HOME, ".local/share/icons")

# Theme preference (lower rank = preferred). Any installed theme is scanned;
# this only decides ties between equally sharp icons, so an icon pack such as
# Kora wins over a 16px Breeze glyph.
PREFERRED = [
    "kora",
    "Win11-black",
    "Win11-black-dark",
    "McMojave-circle-light",
    "McMojave-circle",
    "Papirus",
    "Papirus-Dark",
    "breeze",
    "breeze-dark",
    "hicolor",
    "Adwaita",
    "AdwaitaLegacy",
    "Numix-Circle",
    "Numix-Circle-Light",
]

_roots = []
_rank = 0
# With a prefix the user's own icons are irrelevant: only the staged root counts.
_bases = [rooted("/usr/share/icons")] if PREFIX else [_os.path.join(HOME, ".local/share/icons"), "/usr/share/icons"]
for base in _bases:
    if not _os.path.isdir(base):
        continue
    for name in sorted(_os.listdir(base)):
        d = _os.path.join(base, name)
        if not _os.path.isdir(d):
            continue
        if name in ("default", "breeze_cursors"):
            continue
        try:
            r = PREFERRED.index(name)
        except ValueError:
            r = len(PREFERRED)
        _roots.append((d, r))
        _rank += 1

PIXMAP_ROOTS = [rooted("/usr/share/pixmaps")] if PREFIX else \
               [_os.path.join(HOME, ".local/share/pixmaps"), "/usr/share/pixmaps"]
ROOTS = _roots + [(p, len(PREFERRED) + 5 + i) for i, p in enumerate(PIXMAP_ROOTS)]
SUBDIRS = ("apps","status","devices","places","actions","categories","mimetypes","preferences","legacy","symbolic","notifications","panel","emotes")

best = {}
def score(ext, depth, rootrank, path):
    # prefer svg, then larger png, then preferred roots
    s = 0
    if ext == ".svg":
        s += 1000
    else:
        try:
            px = int(path.split("/")[-2].split("x")[0])
        except Exception:
            px = 0
        s += px
    s -= rootrank * 40
    return s

for root, rank in ROOTS:
    if not os.path.isdir(root):
        continue
    if root.endswith("pixmaps"):
        for f in os.listdir(root):
            if f.lower().endswith((".svg", ".png")):
                name = os.path.splitext(f)[0]
                p = os.path.join(root, f)
                sc = score(os.path.splitext(f)[1].lower(), 0, rank, p)
                if name not in best or sc > best[name][0]:
                    best[name] = (sc, p)
        continue
    for dirpath, dirnames, filenames in os.walk(root):
        rel = os.path.relpath(dirpath, root)
        parts = rel.split(os.sep)
        if rel != "." and not any(x in SUBDIRS for x in parts):
            continue
        for f in filenames:
            ext = os.path.splitext(f)[1].lower()
            if ext not in (".svg", ".png"):
                continue
            name = os.path.splitext(f)[0]
            p = os.path.join(dirpath, f)
            sc = score(ext, len(parts), rank, p)
            if name not in best or sc > best[name][0]:
                best[name] = (sc, p)

m = {k: v[1] for k, v in best.items()}
# Strip the staging prefix so the map holds runtime paths (/usr/share/...).
if PREFIX:
    _pref = PREFIX.rstrip("/")
    m = {k: (v[len(_pref):] if v.startswith(_pref) else v) for k, v in m.items()}
import sys
out = sys.argv[1] if len(sys.argv) > 1 else "/run/media/raf/Z/Willow-Canopy/shell/icon-map.js"
with open(out, "w") as fh:
    fh.write("// Generated by scripts/gen-icon-map.py - do not edit\n")
    fh.write(".pragma library\n")
    fh.write("var map = ")
    json.dump(m, fh, separators=(",", ":"))
    fh.write(";\n")
print("icons:", len(m))
for t in ("firefox","thunar","code-oss","kitty","network-wireless","audio-volume-high","bluetooth-active","battery","preferences-system","view-app-grid","system-lock-screen","system-log-out","application-x-executable"):
    print(t, "->", m.get(t, "MISSING"))
